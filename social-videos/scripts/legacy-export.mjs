// macOS 12 cannot load AVFoundation symbols required by Remotion's bundled
// multimedia binaries. Render images in Chromium, then mux with static FFmpeg.
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
const require=createRequire(import.meta.url);
function interpolate(x,keys,values){
  if(x<=keys[0])return values[0];
  for(let i=1;i<keys.length;i++)if(x<=keys[i])return values[i-1]+(values[i]-values[i-1])*(x-keys[i-1])/(keys[i]-keys[i-1]);
  return values.at(-1);
}
export async function encodeLegacy(root,v,frames,output){
  if((!v.music&&!v.voice&&v.effects===false)||v.renderer==='snack-engine-demo'){
    const images=(await readdir(frames)).filter(n=>/^element-\d+\.jpeg$/.test(n)).sort();
    if(images.length!==v.duration*30)throw Error('Incomplete frame sequence');
    const padding=images[0].match(/element-(\d+)/)[1].length;
    const result=spawnSync(require('@ffmpeg-installer/ffmpeg').path,['-y','-framerate','30','-i',path.join(frames,`element-%0${padding}d.jpeg`),'-an','-c:v','libx264','-preset','fast','-crf','18','-pix_fmt','yuv420p','-movflags','+faststart',output],{stdio:'inherit'});
    if(result.status!==0)throw Error('Silent encoding failed');
    return;
  }
  if(v.id!=='01-decoupe-37')throw Error('Legacy audio mix is only available for the cut demo.');
  const images=(await readdir(frames)).filter(n=>/^element-\d+\.jpeg$/.test(n)).sort();
  if(images.length!==v.duration*30)throw Error('Incomplete frame sequence');
  const padding=images[0].match(/element-(\d+)/)[1].length;
  const rate=44100,count=rate*v.duration,mix=new Float32Array(count);
  async function add(file,at,gain){
    const b=await readFile(path.join(root,'public',file));
    // These files are the canonical mono PCM16 WAVs generated by this project.
    if(b.toString('ascii',0,4)!=='RIFF'||b.readUInt32LE(24)!==rate||b.readUInt16LE(22)!==1||b.toString('ascii',36,40)!=='data')throw Error('Unsupported generated WAV format');
    const start=Math.round(at*rate);
    for(let i=0;i<(b.length-44)/2&&i+start<count;i++)mix[i+start]+=b.readInt16LE(44+i*2)/32768*gain((i+start)/rate*30);
  }
  if(v.music)await add(v.music,0,f=>.18*interpolate(f,[0,12,195,211,264,350,450],[0,1,1,.3,.65,.65,0]));
  for(const [name,frame,gain] of [['cut-sweep',82,.4],['select',155,.35],['lock',195,.4],['reveal',211,.45]])await add(`audio/${name}.wav`,frame/30,()=>gain);
  const pcm=Buffer.alloc(count*2);let peak=0;
  mix.forEach((value,i)=>{peak=Math.max(peak,Math.abs(value));pcm.writeInt16LE(Math.round(Math.max(-1,Math.min(1,value))*32767),i*2);});
  if(peak>=1)throw Error('Clipping in generated mix');
  const header=Buffer.from((await readFile(path.join(root,'public/audio/slaptax-pulse.wav'))).subarray(0,44));
  header.writeUInt32LE(36+pcm.length,4);header.writeUInt32LE(pcm.length,40);
  const soundtrack=path.join(path.dirname(output),'soundtrack.wav');
  await writeFile(soundtrack,Buffer.concat([header,pcm]));
  const ffmpeg=require('@ffmpeg-installer/ffmpeg').path;
  const args=['-y','-framerate','30','-i',path.join(frames,`element-%0${padding}d.jpeg`),'-i',soundtrack];
  if(v.voice)args.push('-i',path.join(root,'public',v.voice),'-filter_complex','[2:a]adelay=267|267[voice];[1:a][voice]amix=inputs=2:normalize=0[a]','-map','0:v','-map','[a]');
  args.push('-t',String(v.duration),'-c:v','libx264','-preset','fast','-crf','18','-pix_fmt','yuv420p','-c:a','aac','-b:a','192k','-movflags','+faststart',output);
  const result=spawnSync(ffmpeg,args,{stdio:'inherit'});
  if(result.error)throw result.error;
  if(result.status!==0)throw Error(`Static FFmpeg failed (${result.status})`);
  console.log(`Export ready. Generated soundtrack peak: ${peak.toFixed(3)} (no clipping).`);
}
